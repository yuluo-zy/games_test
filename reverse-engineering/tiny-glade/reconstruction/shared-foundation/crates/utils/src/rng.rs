//! Private seed transform; output is the observed initial fastrand state.
//! Original fastrand 1.8.0 with_seed/seed stores that state directly. Generation,
//! distributions and shuffling remain entirely in the original dependency.
pub fn init_rng_u64(seed:u64)->u64 {
    seed.wrapping_mul(0x7598_39da_217f).wrapping_add(0x0001_3c7c_a929_3765)^0x4d59_5df4_d0f3_3173
}
pub fn init_rng(seed:u32)->u64 {init_rng_u64(u64::from(seed))}
/// Typed producer adapter over the recovered state transform. No second game
/// transform is applied: fastrand's original with_seed simply stores the u64.
pub fn rng_from_seed_u64(seed:u64)->fastrand::Rng {
    fastrand::Rng::with_seed(init_rng_u64(seed))
}

