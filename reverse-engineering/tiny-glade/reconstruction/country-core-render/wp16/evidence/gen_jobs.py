#!/usr/bin/env python3
"""Generate ghidra get_functions jobs from RVA lists (adds image base)."""
import json

BASE = 0x140000000
FIELDS = "signature,decompiled_code"


def make_job(out, rvas):
    funcs = ",".join(f"{BASE + rva:#x}" for rva in rvas)
    job = [
        {
            "tool": "get_functions",
            "args": {
                "program": "tiny-glade.exe",
                "functions": funcs,
                "fields": FIELDS,
                "include_call_context": False,
            },
            "timeout_seconds": 300,
        }
    ]
    with open(out, "w") as f:
        json.dump(job, f, indent=2)
    print(f"wrote {out} with {len(rvas)} funcs")


