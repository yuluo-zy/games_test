import {run} from '../../../scripts/render-recovery/mcp-evidence-job.mjs';
import {readFileSync,writeFileSync,mkdirSync,existsSync,rmSync,readdirSync} from 'node:fs';
import {resolve,dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const base=dirname(fileURLToPath(import.meta.url)),fixture=join(base,'fixture');
assert.equal(resolve(fixture),resolve(base,'fixture'));
if(existsSync(fixture))rmSync(fixture,{recursive:true});
mkdirSync(fixture,{recursive:true});
const target=join(fixture,'target.bin'),input=join(fixture,'input.txt'),manifest=join(fixture,'provider-manifest.json'),snapshot=join(fixture,'database-snapshot.json');
writeFileSync(target,'fixture-target-v1');writeFileSync(input,'input-v1');
writeFileSync(manifest,JSON.stringify({provider:'local-fake',version:'1'}));writeFileSync(snapshot,JSON.stringify({database:'fixture',revision:1}));
const checks=[];
const check=(name,condition)=>{assert.ok(condition,name);checks.push({name,ok:true});};
const config={command:process.execPath,args:[join(base,'fake-mcp.mjs')]};
const job=(name,steps)=>({target:{path:target},provider:{id:'local-fake',version:'1'},database:'fixture',session_key:'fake:'+name,inputs:[{path:input}],cache_context:{provider_manifest:manifest,database_snapshot:snapshot},cache_dir:join(fixture,'cache'),lock_dir:join(fixture,'locks'),steps});
const steps=[{tool:'open_database',args:{database_id:'fixture',file_path:target,run_auto_analysis:false}},{tool:'decompile_function',args:{database:'fixture',address:'0x123'}},{tool:'get_xrefs_to',args:{database:'fixture',address:'0x123'}}];
const execute=async(name,j)=>run('fake',j,join(base,name+'.json'),config);
const a=await execute('success',job('normal',steps));
check('real_local_protocol_connection',a.ok&&a.actual_mcp_connection&&a.catalog[0].tools.length===4);
check('default_cleanup_save_false',a.cleanup.length===1&&a.cleanup[0].args.save===false&&a.cleanup_ok);
check('complete_result_and_xref_limits',a.results[1].result.content[0].text&&a.results[2].coverage.completeness==='unknown');
check('lock_released',!existsSync(a.lock_events[0].path));
const b=await execute('cached',job('normal',steps));
check('successful_analysis_reused_lifecycle_called',b.ok&&b.results[0].source==='actual_mcp_call'&&b.results[1].source==='retained_success');
writeFileSync(input,'input-v2');const c=await execute('input-invalidated',job('normal',steps));
check('input_hash_invalidates_cache',c.ok&&c.results[1].source==='actual_mcp_call'&&c.results[1].cache_key!==b.results[1].cache_key);
writeFileSync(target,'fixture-target-v2');const d=await execute('target-invalidated',job('normal',steps));
check('target_hash_invalidates_cache',d.ok&&d.results[1].cache_key!==c.results[1].cache_key);
const different=job('normal',steps);different.provider.version='2';const e=await execute('provider-invalidated',different);
check('provider_version_invalidates_cache',e.ok&&e.results[1].cache_key!==d.results[1].cache_key);
const failSteps=[steps[0],{tool:'decompile_function',args:{fail:true}}];
const f=await execute('error-envelope',job('error',failSteps));
check('tool_failure_recorded_and_cleaned',!f.ok&&f.cleanup_ok&&f.results[1].ok===false&&f.cleanup[0].args.save===false);
check('error_not_cached',!existsSync(join(fixture,'cache',f.results[1].cache_key+'.json')));
const g=await execute('protocol-error',job('protocol',[steps[0],{tool:'decompile_function',args:{throw:true}}]));
check('protocol_exception_recorded_and_cleaned',!g.ok&&g.cleanup_ok&&g.results[1].error);
const h=await execute('timeout',job('timeout',[steps[0],{tool:'decompile_function',timeout_ms:50,args:{delay_ms:1500}}]));
check('timeout_recorded_and_cleaned',!h.ok&&h.cleanup_ok&&h.results[1].error);
const closeJob=job('quarantine',[{...steps[0],args:{...steps[0].args,database_id:'fail-close'}},{tool:'decompile_function',args:{database:'fail-close'}}]);closeJob.database='fail-close';
const i=await execute('cleanup-failure',closeJob);
check('failed_cleanup_quarantines_lock',!i.ok&&!i.cleanup_ok&&existsSync(join(i.lock_events[0].path,'quarantine.json')));
check('failed_session_commits_no_success_cache',!existsSync(join(fixture,'cache',i.results[1].cache_key+'.json')));
const j=await execute('lock-busy',closeJob);
check('busy_lock_prevents_connection',!j.ok&&!j.actual_mcp_connection&&j.lock_events[0].event==='busy');
// Remove only the verified fixture lock left by this test; no provider database exists.
assert.ok(resolve(i.lock_events[0].path).startsWith(resolve(fixture)+'\\')||resolve(i.lock_events[0].path).startsWith(resolve(fixture)+'/'));
rmSync(i.lock_events[0].path,{recursive:true});
const mismatch=job('wrong-target',steps);mismatch.target.sha256='0'.repeat(64);
const k=await execute('wrong-target',mismatch);
check('wrong_expected_identity_prevents_connection',!k.ok&&!k.actual_mcp_connection&&k.error.includes('target hash'));
const reuseJob=job('normal',[steps[0],{...steps[1],reuse:{report:join(base,'target-invalidated.json'),index:1}}]);
// Remove the matching successful cache to exercise explicit retained report reuse.
const cachePath=join(fixture,'cache',d.results[1].cache_key+'.json');if(existsSync(cachePath))rmSync(cachePath);
const l=await execute('report-reuse',reuseJob);
check('identified_retained_report_reused',l.ok&&l.results[1].source==='retained_success'&&l.results[1].reused_from.endsWith('target-invalidated.json'));
const explicitClose=await execute('explicit-close',job('explicit',[steps[0],{tool:'close_database',args:{database:'fixture'}}]));
check('explicit_close_defaults_save_false',explicitClose.ok&&explicitClose.results[1].args.save===false&&explicitClose.cleanup.length===0);
const noContext=job('no-context',steps);delete noContext.cache_context;
const n=await execute('no-cache-context',noContext);const n2=await execute('no-cache-context-repeat',noContext);
check('missing_db_provider_context_disables_reuse',n.ok&&n2.ok&&!n.cache_policy.enabled&&n2.results[1].source==='actual_mcp_call');
writeFileSync(snapshot,JSON.stringify({database:'fixture',revision:2}));
const revised=await execute('db-revision-invalidated',job('normal',steps));
check('database_revision_hash_invalidates',revised.ok&&revised.results[1].source==='actual_mcp_call'&&revised.results[1].cache_key!==l.results[1].cache_key);
for(const tool of ['execute','set_type','run_target','save_database']){
 const denied=await execute('denied-'+tool,job('deny',[{tool,args:{}}]));
 check('read_only_allowlist_denies_'+tool,!denied.ok&&!denied.actual_mcp_connection&&denied.error.includes('allowlist'));
}
const saveDenied=await execute('denied-save-true',job('deny',[steps[0],{tool:'close_database',args:{database:'fixture',save:true}}]));
check('save_true_rejected_before_connection',!saveDenied.ok&&!saveDenied.actual_mcp_connection);
check('server_version_actual_recorded',a.actual_server.name==='local-fake-mcp'&&a.actual_server.version==='1');
check('recursive_lock_delete_boundary_verified',a.lock_events.at(-1).path_boundary_verified===true);
const sources=Object.fromEntries([resolve(base,'../../../scripts/render-recovery/mcp-evidence-job.mjs'),join(base,'fake-mcp.mjs'),fileURLToPath(import.meta.url)].map(path=>[path,createHash('sha256').update(readFileSync(path)).digest('hex')]));
const summary={schema_version:1,fixture_only:true,original_target_connected:false,ghidra_opened:false,sources,checks,passed:checks.length,failed:0,cache_entries:readdirSync(join(fixture,'cache')).length};
writeFileSync(join(base,'runner-validation.json'),JSON.stringify(summary,null,2)+'\n');
console.log(JSON.stringify(summary));
