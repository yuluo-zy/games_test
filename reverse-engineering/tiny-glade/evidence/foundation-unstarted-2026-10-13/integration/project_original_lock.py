"""Project original external records into the recovered workspace's own lock.
Keep local recovered package records; never install the whole original game lock.
Cargo must resolve/prune and a subsequent identity audit must pass.
"""
import hashlib,json,tomllib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3]
DEST=ROOT/'reconstruction/shared-foundation/Cargo.lock'
ORIG=ROOT/'tracking/original-Cargo.lock'
OUT=Path(__file__).resolve().parent
current_text=DEST.read_text(encoding='utf-8')
original_text=ORIG.read_text(encoding='utf-8')
current=tomllib.loads(current_text)['package']
original=tomllib.loads(original_text)['package']
def key(p): return (p['name'],p['version'],p.get('source',''))
by_name={}
for p in original: by_name.setdefault(p['name'],[]).append(p)
def original_dep(dep):
    bits=dep.split(' (',1)[0].split()
    rows=by_name.get(bits[0],[])
    if len(bits)>1: rows=[r for r in rows if r['version']==bits[1]]
    if ' (' in dep: rows=[r for r in rows if r.get('source')==dep.split(' (',1)[1].removesuffix(')')]
    if len(rows)!=1: raise ValueError(('ambiguous_original_dependency',dep,[key(r) for r in rows]))
    return rows[0]
def compatible(v,o):
    a=v.split('+')[0].split('.');b=o.split('+')[0].split('.')
    return a[:1]==b[:1] if a[0]!='0' else a[:2]==b[:2]
locals=[p for p in current if not p.get('source')]
current_by_name={}
for p in current: current_by_name.setdefault(p['name'],[]).append(p)
seeds=[]
retained_existing_candidate=[]
for local in locals:
    for dep in local.get('dependencies',[]):
        bits=dep.split(' (',1)[0].split(); rows=current_by_name.get(bits[0],[])
        if len(bits)>1: rows=[r for r in rows if r['version']==bits[1]]
        if len(rows)!=1: raise ValueError(('ambiguous_current_dependency',local['name'],dep))
        c=rows[0]
        if not c.get('source'): continue
        candidates=[o for o in by_name.get(c['name'],[]) if o.get('source') and o['version']==c['version']]
        if not candidates: candidates=[o for o in by_name.get(c['name'],[]) if o.get('source') and compatible(c['version'],o['version'])]
        if not candidates and local['name']=='rhapsody' and key(c)==('gpu-allocator','0.27.0','registry+https://github.com/rust-lang/crates.io-index'):
            retained_existing_candidate.append(c)
            seeds.extend(original_dep(d) for d in c.get("dependencies",[]))
            continue
        if len(candidates)>1:
            source=c.get('source','')
            exact=[o for o in candidates if o.get('source')==source]
            if exact: candidates=exact
        if len(candidates)!=1: raise ValueError(('no_unique_original_direct_identity',local['name'],key(c),[key(o) for o in candidates]))
        seeds.extend(candidates)
selected={}
pending=seeds[:]
while pending:
    p=pending.pop()
    if key(p) in selected: continue
    if not p.get('source'): raise ValueError(('unexpected_original_local_package',key(p)))
    selected[key(p)]=p
    pending.extend(original_dep(d) for d in p.get('dependencies',[]))
raw_orig={key(tomllib.loads('[[package]]'+b)['package'][0]):b.strip() for b in original_text.split('[[package]]')[1:]}
raw_cur={key(tomllib.loads('[[package]]'+b)['package'][0]):b.strip() for b in current_text.split('[[package]]')[1:]}
records=[(key(p),raw_cur[key(p)]) for p in locals+retained_existing_candidate]+[(k,raw_orig[k]) for k in selected]
for p in retained_existing_candidate:
    for dep in p.get('dependencies',[]):
        row=original_dep(dep)
        if key(row) not in selected: raise ValueError(('candidate_missing_dependency',key(row)))
text='# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n'+'\n\n'.join('[[package]]\n'+raw for k,raw in sorted(records))+'\n'
(OUT/'pre-projection-Cargo.lock').write_text(current_text,encoding='utf-8')
DEST.write_text(text,encoding='utf-8',newline='\n')
report={'original_lock_sha256':hashlib.sha256(ORIG.read_bytes()).hexdigest(),'previous_lock_sha256':hashlib.sha256(current_text.encode()).hexdigest(),'projected_lock_sha256':hashlib.sha256(text.encode()).hexdigest(),'local_records_preserved':[p['name'] for p in locals],'external_records_seeded':len(selected),'retained_existing_candidate_dependencies':[key(p) for p in retained_existing_candidate],'whole_original_lock_installed':False,'original_game_local_packages_added':False,'validation_required':'Cargo resolution followed by exact public dependency identity audit'}
(OUT/'lock-projection.json').write_text(json.dumps(report,indent=2)+'\n',encoding='utf-8')
print(json.dumps(report))
