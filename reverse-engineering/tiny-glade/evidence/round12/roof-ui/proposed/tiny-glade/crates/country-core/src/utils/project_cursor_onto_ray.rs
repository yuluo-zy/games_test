//! 三维编辑滑块的坐标转换与透视校正。矩阵运算复用 glam。

use glam::{Mat4, Vec2, Vec3};
use utils::geometry::Ray;

const MIN_PROJECTED_LENGTH_SQUARED: f32 = 1e-20;
const MIN_CLIP_WEIGHT: f32 = 1e-10;

/// 比例屏幕空间：X 乘宽高比，Y 保持单位尺度。
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ProportionalScreenSpace {
    pub size: Vec2,
    pub aspect: f32,
    pub unit: f32,
}

impl ProportionalScreenSpace {
    /// Original140ac8420 converts both u32 dimensions directly, including zero.
    pub fn from_window_size(size: [u32; 2]) -> Self {
        let size = Vec2::new(size[0] as f32, size[1] as f32);
        Self {
            size,
            aspect: size.x / size.y,
            unit: 1.0,
        }
    }

    /// 像素原点在左上；屏幕中心映射到零点，上方为正 Y。
    pub fn transform_screen_space(&self, screen_x: f32, screen_y: f32) -> Vec2 {
        // B140c906d0: its Y expression is intentionally (1-y)/height,
        // then doubled and incremented. Do not replace by conventional NDC.
        let x = screen_x / self.size.x;
        let y = (1.0 - screen_y) / self.size.y;
        Vec2::new((x + x - 1.0) * self.aspect, (y + y + 1.0) * self.unit)
    }
}

/// 已转换的比例屏幕坐标。
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ProportionalScreenSpaceCoord(pub Vec2);

impl ProportionalScreenSpaceCoord {
    /// Original723B projection with exact perspective correction and MAXSS policy.
    /// The optional defensive adapter below is a separate host API.
    pub fn project_onto_ray(
        self,
        screen: &ProportionalScreenSpace,
        world_to_view: &Mat4,
        view_to_clip: &Mat4,
        ray: Ray,
        range: [f32; 2],
    ) -> Vec3 {
        assert!(range[0] <= range[1], "投影范围逆序或包含 NaN：{range:?}");
        // Original140ac84a0: no behind-camera, finite-value or fallback
        // branches. These two MAXSS constants are from original RNE bytes.
        let near = ray.origin;
        let far = ray.origin + ray.direction;
        let project = |point: Vec3| {
            let view = world_to_view.transform_point3(point);
            *view_to_clip * view.extend(1.0)
        };
        let a = project(near);
        let b = project(far);
        let scale = Vec2::new(screen.aspect, screen.unit);
        let start = a.truncate().truncate() / a.w * scale;
        let end = b.truncate().truncate() / b.w * scale;
        let direction = end - start;
        let numerator = (self.0 - start) * direction;
        let squared = direction * direction;
        let divisor = if squared.x + squared.y > MIN_PROJECTED_LENGTH_SQUARED {
            squared.x + squared.y
        } else {
            MIN_PROJECTED_LENGTH_SQUARED
        };
        let parameter = (numerator.x + numerator.y) / divisor;
        // MAXSS/MINSS select their second operand on equality or unordered.
        let parameter = if range[0] > parameter {
            range[0]
        } else {
            parameter
        };
        let parameter = if range[1] < parameter {
            range[1]
        } else {
            parameter
        };
        let inverse_a = 1.0 / a.w;
        let inverse_b = 1.0 / b.w;
        let numerator = 0.0 / a.w + (inverse_b - 0.0 / a.w) * parameter;
        let denominator = inverse_a + (inverse_b - inverse_a) * parameter;
        let denominator = if denominator > MIN_CLIP_WEIGHT {
            denominator
        } else {
            MIN_CLIP_WEIGHT
        };
        let weight = numerator / denominator;
        // Match native interpolation, including cancellation and signed zero.
        near * (1.0 - weight) + far * weight
    }

    /// 将光标投影到射线的屏幕方向，再使用裁剪 w 校正为世界空间插值参数。
    /// range 限制的是屏幕参数；零投影长度保持起点，视点后方或奇异透视返回 None。
    pub fn try_project_onto_ray(
        self,
        screen: &ProportionalScreenSpace,
        world_to_view: &Mat4,
        view_to_clip: &Mat4,
        ray: Ray,
        range: [f32; 2],
    ) -> Option<Vec3> {
        let [minimum, maximum] = range;
        if !(minimum.is_finite() && maximum.is_finite() && minimum <= maximum)
            || !self.0.is_finite()
            || !ray.origin.is_finite()
            || !ray.direction.is_finite()
            || !screen.aspect.is_finite()
            || !screen.unit.is_finite()
        {
            return None;
        }
        let near_clip = *view_to_clip * (*world_to_view * ray.origin.extend(1.0));
        let far_clip = *view_to_clip * (*world_to_view * (ray.origin + ray.direction).extend(1.0));
        if !near_clip.is_finite()
            || !far_clip.is_finite()
            || near_clip.w <= MIN_CLIP_WEIGHT
            || far_clip.w <= MIN_CLIP_WEIGHT
        {
            return None;
        }
        let screen_scale = Vec2::new(screen.aspect, screen.unit);
        let near_screen = near_clip.truncate().truncate() / near_clip.w * screen_scale;
        let far_screen = far_clip.truncate().truncate() / far_clip.w * screen_scale;
        let projected_direction = far_screen - near_screen;
        let length_squared = projected_direction.length_squared();
        if !length_squared.is_finite() {
            return None;
        }
        if length_squared <= MIN_PROJECTED_LENGTH_SQUARED {
            return Some(ray.origin);
        }
        let screen_parameter = ((self.0 - near_screen).dot(projected_direction) / length_squared)
            .clamp(minimum, maximum);
        let near_weight = (1.0 - screen_parameter) / near_clip.w;
        let far_weight = screen_parameter / far_clip.w;
        let total_weight = near_weight + far_weight;
        // 外推可能跨过透视奇点；负权重对应相机背后的另一条分支。
        if !total_weight.is_finite() || total_weight <= MIN_CLIP_WEIGHT {
            return None;
        }
        let world_parameter = far_weight / total_weight;
        let position = ray.origin + ray.direction * world_parameter;
        if !position.is_finite() {
            return None;
        }
        let clip = *view_to_clip * (*world_to_view * position.extend(1.0));
        (clip.is_finite() && clip.w > MIN_CLIP_WEIGHT).then_some(position)
    }
}

