//! Original B wall-input resampling, using the existing clock and camera.
//! 0x14145c350; the previous point is the last accepted point, not the last
//! attempted point. Neither a zero tick frame nor a rejected endpoint moves it.

use glam::{Vec2, Vec3};

use crate::{
    resources::{time::GameTime, window::WindowSize},
    systems::camera_rig::main_camera::MainCamera,
};

#[derive(Clone, Debug, Default)]
pub struct DrawingInputSmoother {
    pub previous: Option<Vec2>,
}

#[derive(Clone, Debug, Default)]
pub struct RawInputSmoothed {
    points: Vec<Vec2>,
}

impl RawInputSmoothed {
    pub fn points(&self) -> &[Vec2] {
        &self.points
    }
    pub fn is_empty(&self) -> bool {
        self.points.is_empty()
    }
    pub fn point_count(&self) -> usize {
        self.points.len()
    }
}

impl DrawingInputSmoother {
    pub fn new(previous: Option<Vec2>) -> Self {
        Self { previous }
    }

    pub fn process(
        &mut self,
        current: Vec3,
        time: &GameTime,
        camera: &MainCamera,
        window: &WindowSize,
    ) -> RawInputSmoothed {
        // Original matrix block +0x80 is the view matrix. Keep the observed
        // scalar evaluation order and reuse the current camera's read API.
        let view_z = ((camera.read_f32(0x88) * current.x + camera.read_f32(0x98) * current.y)
            + camera.read_f32(0xa8) * current.z)
            + camera.read_f32(0xb8);
        let pixel_scale = ((0.5 / -view_z) * camera.read_f32(0x14)) * window.height as f32;
        let current = Vec2::new(current.x, current.z);
        let initial = self.previous.unwrap_or(current);
        let count = time.ticks_60;
        let mut points = Vec::new();
        for index in 1..=count {
            let t = index as f32 / count as f32;
            let point = current * t + initial * (1.0 - t);
            if let Some(previous) = self.previous {
                let delta = point - previous;
                let distance = (delta.y * delta.y + delta.x * delta.x).sqrt();
                // Ordered, strict comparisons also reject unordered NaNs.
                if !(distance > 0.01 && distance * pixel_scale > 3.0) {
                    continue;
                }
            }
            points.push(point);
            self.previous = Some(point);
        }
        RawInputSmoothed { points }
    }
}

