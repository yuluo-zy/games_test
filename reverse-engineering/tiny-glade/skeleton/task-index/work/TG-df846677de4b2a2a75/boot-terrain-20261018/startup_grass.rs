//! Original B startup_grass @140a21620 (1027B). This producer belongs to
//! OnEnter(AppLoadingState::Game), not the independent eight-item Startup tuple.
//! It registers the W9 object-push shader and creates both actual grass drawables.
use crate::{
    asset_libraries::{
        mesh_library::{AssetMeshLibrary, MeshAsset},
        meshwatch::MeshWatch,
        shader_library::AssetShaderLibrary,
    },
    components::drawable::DrawableMeshBundle,
    render::{mesh::Mesh, shader::boundary::ShaderBackend},
    systems::render_loop::draw_passes::{
        draw_lists::{DesignatedRenderPass, DontCastShadow},
        draw_shaders::startup_quad::quad_window_indices,
    },
    utils::components::transform::Transform,
};
use bevy_ecs::system::Commands;
use itertools::Itertools;

pub const GRASS_BLADE_MESH_NAME: &str = "grass_blade";
pub const GRASS_DRAW_LIST: u32 = 7;
pub const OBJECT_PUSH_SHADER: (&str, &str) =
    ("/grass_object_push.raster.hlsl", "grass_object_push");
pub const DRAW_SHADERS: [(&str, &str); 2] = [
    ("/grass.raster.hlsl", "grass_shader"),
    ("/grass_lod1.raster.hlsl", "grass_lod1_shader"),
];

/// Original RangeInclusive0..=5 -> adjacent pairs -> six indices per pair,
/// then Take27. The fifth pair contributes only its first triangle. Vertices
/// are generated by the original shader's vertex ID; do not synthesize attrs.
pub fn grass_blade_mesh() -> Mesh {
    let mut mesh = Mesh::new("grass blade");
    mesh.set_indices(
        (0u32..=5)
            .tuple_windows::<(u32, u32)>()
            .flat_map(quad_window_indices)
            .take(27)
            .collect(),
    );
    mesh
}

/// All libraries and Commands belong to the actual gameplay App. ShaderBackend
/// is the existing current-host adaptation of the original GraphicsDevice /
/// shader-loader boundary; no extra device or fallback shader is created.
/// Calls preserve original order and keep real mesh/shader handles in bundles.
pub fn startup_grass(
    meshes: &AssetMeshLibrary,
    mesh_watch: &MeshWatch,
    shaders: &AssetShaderLibrary,
    backend: &dyn ShaderBackend,
    commands: &mut Commands,
) {
    super::load_shaders::load_shader_into_library(
        shaders,
        backend,
        OBJECT_PUSH_SHADER.0,
        OBJECT_PUSH_SHADER.1,
    );
    let mesh = grass_blade_mesh();
    // Exact common load_mesh_into_library @140b1aca0: watch, then add.
    // This procedural mesh has source_file=None, a legal watcher no-op.
    mesh_watch.watch(&mesh);
    let mesh = meshes.add(MeshAsset::new(mesh, Some(GRASS_BLADE_MESH_NAME.to_owned())));
    for (path, name) in DRAW_SHADERS {
        let shader = super::load_shaders::load_shader_into_library(shaders, backend, path, name);
        commands.spawn((
            DrawableMeshBundle {
                mesh,
                shader,
                transform: Transform::identity(),
            },
            DontCastShadow,
            DesignatedRenderPass(GRASS_DRAW_LIST),
        ));
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{
        asset_libraries::Handle,
        render::{shader::RasterShaderProgram, test_device::TestDevice},
    };
    use bevy_ecs::{system::CommandQueue, world::World};

    #[test]
    fn original_27_indices_end_on_fifth_first_triangle_without_attributes() {
        let mesh = grass_blade_mesh();
        assert_eq!(mesh.label, "grass blade");
        assert!(mesh.source_file.is_none());
        assert!(mesh.attributes.is_empty());
        assert_eq!(
            mesh.indices,
            [
                0, 1, 2, 2, 1, 3, 2, 3, 4, 4, 3, 5, 4, 5, 6, 6, 5, 7, 6, 7, 8, 8, 7, 9, 8, 9, 10,
            ]
        );
    }

    #[test]
    fn actual_libraries_and_commands_receive_two_drawables_and_w9_shader() {
        let meshes = AssetMeshLibrary::new();
        let mesh_watch = MeshWatch::new(false);
        let shaders = AssetShaderLibrary::new();
        let device = TestDevice::default();
        let mut world = World::new();
        let mut queue = CommandQueue::default();
        startup_grass(
            &meshes,
            &mesh_watch,
            &shaders,
            &device,
            &mut Commands::new(&mut queue, &world),
        );
        queue.apply(&mut world);
        let mesh = meshes
            .try_get_handle_by_name(GRASS_BLADE_MESH_NAME)
            .unwrap();
        assert_eq!(meshes.get(mesh).unwrap().indices.len(), 27);
        for (path, name) in [OBJECT_PUSH_SHADER, DRAW_SHADERS[0], DRAW_SHADERS[1]] {
            let shader = shaders.get_raster_handle_by_name(name).unwrap();
            assert_eq!(shaders.get_raster(shader).unwrap().desc.path, path);
        }
        let mut query = world.query::<(
            &Handle<Mesh>,
            &Handle<RasterShaderProgram>,
            &Transform,
            &DesignatedRenderPass,
            &DontCastShadow,
        )>();
        let entities: Vec<_> = query.iter(&world).collect();
        assert_eq!(entities.len(), 2);
        let mut names = Vec::new();
        for (actual_mesh, shader, transform, pass, _) in entities {
            assert_eq!(*actual_mesh, mesh);
            assert_eq!(*transform, Transform::identity());
            assert_eq!(pass.0, 7);
            names.push(shaders.get_raster(*shader).unwrap().name);
        }
        names.sort_unstable();
        assert_eq!(names, ["grass_lod1_shader", "grass_shader"]);
    }
}
