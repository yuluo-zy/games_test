fn published_walls() -> PublicWalls {
    let mut inner = InnerWalls::default();
    let curve = Curve2::try_new(vec![[2.25, -4.0], [6.25, -4.0]], false).unwrap();
    inner.new_wall_with_id(WallId(0x9876), WallState::new(curve, 4.0, 0, 0, false));
    let terrain = TerrainHeightGrid512 {
        encoded: vec![0u16; 512 * 512].into(),
        minimum_y: 0.0,
        maximum_y: 0.0,
        sampling_fix: false,
    };
    let mut walls = PublicWalls::default();
    walls.consume(&mut inner, &terrain);
    let wall = walls.get_mut(WallId(0x9876)).unwrap();
    // Post-initialization fixture supplies the independently owned freeform
    // cache. Production lookup/height/world-coordinate functions remain real.
    wall.freeform_heights = Some(FreeformWallHeightCache {
        maximum_y: 2.25,
        arch_segment_heights: vec![2.25; wall.geometry.outline.len()],
        segment_heights: vec![0.0; wall.geometry.outline.len()],
    });
    walls
}
fn u32_at(bytes: &[u8], at: usize) -> u32 {
    u32::from_le_bytes(bytes[at..at + 4].try_into().unwrap())
}
fn u64_at(bytes: &[u8], at: usize) -> u64 {
    u64::from_le_bytes(bytes[at..at + 8].try_into().unwrap())
}
fn f32_at(bytes: &[u8], at: usize) -> f32 {
    f32::from_bits(u32_at(bytes, at))
}
fn info_from_bytes(b: &[u8; 72]) -> DecoratorInfo {
    DecoratorInfo {
        dst_wall: u64_at(b, 0),
        dst_secondary: u64_at(b, 8),
        dst_payload: u64_at(b, 16),
        u18: u64_at(b, 24),
        u20: u32_at(b, 32),
        u24: u32_at(b, 36),
        u28: u32_at(b, 40),
        decorator_id: u32_at(b, 44),
        u30: u64_at(b, 48),
        u38: u32_at(b, 56),
        u3c: u32_at(b, 60),
        u40: u32_at(b, 64),
        rank: b[68],
        u45: b[69],
        ty: b[70],
        state: b[71],
    }
}
fn info_bytes(i: &DecoratorInfo) -> Vec<u8> {
    let mut b = Vec::new();
    for v in [i.dst_wall, i.dst_secondary, i.dst_payload, i.u18] {
        b.extend(v.to_le_bytes());
    }
    for v in [i.u20, i.u24, i.u28, i.decorator_id] {
        b.extend(v.to_le_bytes());
    }
    b.extend(i.u30.to_le_bytes());
    for v in [i.u38, i.u3c, i.u40] {
        b.extend(v.to_le_bytes());
    }
    b.extend([i.rank, i.u45, i.ty, i.state]);
    b
}

#[test]
fn original_move_destination_preserves_all_72_bytes_with_real_published_wall() {
    let walls = published_walls();
    for (before, intent, expected) in MOVES {
        let mut info = info_from_bytes(&before);
        let pair = |at| Vec2::new(f32_at(&intent, at), f32_at(&intent, at + 4));
        let candidate = match u32_at(&intent, 0x20) {
            0 => MoveDstCandidate::Roof(RoofDecoratorDst {
                coord: pair(0x28),
                yaw: DecoratorRotationXZ(f32_at(&intent, 0x24)),
            }),
            1 => MoveDstCandidate::Wall {
                storage: DecoratorStorageAddr::Wall(WallId(u64_at(&intent, 0x18))),
                coordinate: WallSpaceCoord::new_unchecked(
                    f32_at(&intent, 0x28),
                    f32_at(&intent, 0x2c),
                ),
                platform: WallId(u64_at(&intent, 0x30)),
                corner_attachment: intent[0x38],
                bottom_as_door: intent[0x39] != 0,
                compound: intent[0x3a] != 0,
            },
            2 => MoveDstCandidate::Terrain(TerrainDecoratorDst {
                position_xz: pair(0x28),
                yaw: DecoratorRotationXZ(f32_at(&intent, 0x24)),
            }),
            3 => MoveDstCandidate::Stair(StairDecoratorDst {
                first_id: u32_at(&intent, 0x28),
                second_id: u32_at(&intent, 0x2c),
                coordinate: pair(0x30),
                yaw: DecoratorRotationXZ(f32_at(&intent, 0x24)),
            }),
            _ => unreachable!(),
        };
        calculate_move_dst(&mut info, candidate, &walls);
        assert_eq!(info_bytes(&info), expected);
    }
}

#[test]
fn original_grab_offsets_and_same_surface_gates_400_cases() {
    let walls = published_walls();
    let transform = Transform::from_translation(Vec3::new(1.0, 2.0, 3.0));
    for (destination, ty, source, present, offset) in GRABS {
        let info = DecoratorInfo {
            dst_wall: 0x0000000500000003,
            u20: u32::from(destination) << 16,
            ty,
            ..Default::default()
        };
        let hit = RaycastWorldResult {
            handle: source,
            position: Vec3::new(1.25, 2.5, 3.75),
            ..RaycastWorldResult::miss()
        };
        let got = try_get_grab_offset_ss_if_valid(
            &info,
            &transform,
            DecoratorStorageAddr::Wall(WallId(0x9876)),
            &walls,
            Vec2::new(4.0, 5.0),
            |p| Vec2::new(p.x * 2.0 + p.z, p.y * 3.0),
            |delta| {
                assert_eq!(delta, Vec2::ONE);
                hit
            },
            |_, _| panic!("freehand fixture must not access premade trigger"),
        );
        assert_eq!(
            got.is_some(),
            present,
            "destination={destination} type={ty} source={source:?}"
        );
        if let Some(got) = got {
            assert_eq!(got.to_array().map(f32::to_bits), offset);
        }
    }
}

#[test]
fn original_offset_raycast_priority_mask_fallback_24_cases() {
    use std::cell::Cell;
    let mut horizontal_nan_cases = 0;
    for (ty, physical, terrain, dy, mask, tag, position, normal) in OFFSETS {
        let calls = Cell::new(0);
        let ray = utils::geometry::Ray {
            origin: Vec3::new(1.0, 2.0, 3.0),
            direction: Vec3::new(2.0, dy, 4.0),
        };
        let got = select_offset_raycast(
            ray,
            ty,
            |_, got_mask| {
                assert_eq!(got_mask, mask);
                RaycastWorldResult {
                    handle: [0, 0x9876, 0],
                    position: Vec3::new(17.0, 18.0, 19.0),
                    normal: Vec3::new(0.25, 0.5, 0.75),
                    discriminant: if physical { 0 } else { 2 },
                    ..RaycastWorldResult::miss()
                }
            },
            |_| {
                calls.set(calls.get() + 1);
                terrain.then_some(Vec3::new(7.0, 8.0, 9.0))
            },
        );
        assert_eq!(calls.get(), 1);
        assert_eq!(got.handle[0] as u8, tag);
        for (axis, (actual, expected)) in got
            .position
            .to_array()
            .into_iter()
            .zip(position)
            .enumerate()
        {
            let native_horizontal_nan =
                matches!(ty, 56 | 63) && !physical && !terrain && dy.to_bits() == 0 && axis == 1;
            if native_horizontal_nan {
                horizontal_nan_cases += 1;
                assert_eq!(expected, 0xffc0_0000, "只涉及原两处 SSE 算术默认 NaN");
            }
            if !cfg!(target_arch = "x86_64") && native_horizontal_nan {
                // Rust 的跨 ISA 算术 NaN 不保证符号；只排除这一位，载荷与静默位仍逐位核对。
                assert!(actual.is_nan(), "type={ty} axis={axis} 必须仍为 NaN");
                assert_eq!(
                    actual.to_bits() & 0x7fff_ffff,
                    expected & 0x7fff_ffff,
                    "type={ty} axis={axis} NaN 静默位/载荷不得变化"
                );
            } else {
                assert_eq!(
                    actual.to_bits(),
                    expected,
                    "type={ty} axis={axis} 原结果逐位比较"
                );
            }
        }
        assert_eq!(got.normal.to_array().map(f32::to_bits), normal);
    }
    assert_eq!(
        horizontal_nan_cases, 2,
        "必须覆盖 type56 与 type63 两个原零垂直方向用例"
    );
}

