#[test]
fn clear_invalidates_old_keys_and_preserves_capacity() {
    let mut indices = IndexCondenser {
        keys: vec![10u32, 20],
        indices: [(10u32, 0), (20, 1)].into_iter().collect(),
    };
    let a = Condex {
        key: 10,
        cached_index: Cell::new(0),
    };
    let b = Condex {
        key: 20,
        cached_index: Cell::new(1),
    };
    let capacities = (indices.keys.capacity(), indices.indices.capacity());
    indices.clear();
    assert!(indices.keys().is_empty());
    assert_eq!(indices.get(&a), None);
    assert_eq!(indices.get(&b), None);
    assert_eq!(
        (indices.keys.capacity(), indices.indices.capacity()),
        capacities
    );
    indices.keys.push(30);
    indices.indices.insert(30, 0);
    let c = Condex {
        key: 30,
        cached_index: Cell::new(0),
    };
    assert_eq!(indices.get(&c), Some(0));
    assert_eq!(indices.get(&a), None);
}
