//! B's RDP variant: infinite-line distances, optional endpoint spacing, forced
//! first split for strongly bent root chains, and its <=2-left-span shortcut.
use glam::{Vec2, Vec3};
pub trait RdpPoint: Copy {
    fn as_vec3(self) -> Vec3;
}
impl RdpPoint for Vec3 {
    fn as_vec3(self) -> Vec3 {
        self
    }
}
impl RdpPoint for Vec2 {
    fn as_vec3(self) -> Vec3 {
        Vec3::new(self.x, self.y, 0.0)
    }
}
#[derive(Clone, Debug)]
pub struct Rdp<T> {
    pub indices: Vec<usize>,
    pub points: Vec<T>,
}
impl<T: RdpPoint> Rdp<T> {
    /// B's emitted Vec2 producer uses epsilon=0.1 and no endpoint spacing.
    pub fn new(points: &[T]) -> Self {
        Self::new_with_opts(points, 0.1, 0.0)
    }

    /// Keep the old result through `at`, drop the new result's first seam point,
    /// then offset its remaining source indices by the old seam source index.
    /// The first point is dropped unconditionally; no distance-based dedup is
    /// introduced. Inputs must contain the seam and matching points/indices.
    pub fn stitch_with(&self, at: usize, other: &Self) -> Self {
        let mut points = self.points[..=at].to_vec();
        points.extend_from_slice(&other.points[1..]);
        let base = self.indices[at];
        let mut indices = self.indices[..=at].to_vec();
        indices.extend(
            other.indices[1..]
                .iter()
                .map(|&index| index.wrapping_add(base)),
        );
        Self { indices, points }
    }
    pub fn new_with_opts(points: &[T], epsilon: f32, min_endpoint_distance: f32) -> Self {
        if points.len() < 3 {
            return Self {
                indices: (0..points.len()).collect(),
                points: points.to_vec(),
            };
        }
        let root_distance = (points[0].as_vec3() - points[points.len() - 1].as_vec3()).length();
        let mut force_root = root_distance < 1e8;
        let spacing_squared = min_endpoint_distance * min_endpoint_distance;
        let mut indices = vec![0];
        let mut pending = vec![(0, points.len() - 1)];
        while let Some((first, last)) = pending.pop() {
            if last - first < 2 {
                indices.push(last);
                continue;
            }
            let a = points[first].as_vec3();
            let b = points[last].as_vec3();
            let line = b - a;
            let denom = line.length_squared().max(1e-20);
            let mut maximum = 0.0;
            let mut split_offset = 0;
            for (offset, point) in points[first + 1..last].iter().enumerate() {
                let p = point.as_vec3();
                let ratio = (p - a).dot(line) / denom;
                let projection = b * ratio + a * (1.0 - ratio);
                let distance = (p - projection).length();
                assert!(distance.is_finite(), "RDP distance is not finite");
                let has_spacing = spacing_squared == 0.0
                    || ((p - a).length_squared() >= spacing_squared
                        && (p - b).length_squared() >= spacing_squared);
                if distance > maximum && has_spacing {
                    maximum = distance;
                    split_offset = offset + 1;
                }
            }
            if maximum > epsilon || (force_root && maximum > root_distance) {
                let split = first + split_offset;
                pending.push((split, last));
                if split_offset < 3 {
                    indices.push(split);
                } else {
                    pending.push((first, split));
                }
                force_root = false;
            } else {
                indices.push(last);
            }
        }
        let simplified = indices.iter().map(|&i| points[i]).collect();
        Self {
            indices,
            points: simplified,
        }
    }
}

